def match_prefix(code: str, rules: list[tuple[str, list]]) -> list:
    """Собирает значения всех правил, чей префикс совпадает с кодом ОКВЭД.

    Коды ОКВЭД иерархичны посимвольно: 46.38 входит в группу 46.3, а 46.71.2 — в 46.71,
    поэтому достаточно обычного startswith.
    """
    out: list = []
    for prefix, values in rules:
        if code.startswith(prefix):
            for v in (values if isinstance(values, list) else [values]):
                if v not in out:
                    out.append(v)
    return out


